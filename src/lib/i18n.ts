export type MessageKey = keyof typeof en;
export type Dictionary = Record<MessageKey, string>;

const dictionaries: Record<string, Dictionary> = { en };
const dateLocales: Record<string, Locale> = { en: enCA };

/** Current UI language. Later: read from member/user preference or Accept-Language. */
export const LANG = "en";

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const dict = dictionaries[LANG] ?? en;
  let s: string = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export const dateLocale: Locale = dateLocales[LANG] ?? enCA;
